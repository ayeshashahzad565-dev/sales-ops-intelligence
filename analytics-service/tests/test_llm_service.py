def test_no_future_data_reaches_the_model_from_the_live_warehouse(settings):
    """The SQL bounds it; this proves it end to end against real rows."""
    import re

    provider = good_provider()
    run(settings, provider, only_dates=[LIVE_CRITICAL])

    _, user_message = provider.calls[0]
    history_block = user_message.split("HISTORICAL COMPARISON")[1].split("[source:")[0]

    dates = [
        date.fromisoformat(match)
        for match in re.findall(r"\d{4}-\d{2}-\d{2}", history_block)
    ]

    assert dates
    assert all(observed < LIVE_CRITICAL for observed in dates)


