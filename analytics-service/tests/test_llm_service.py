def test_a_second_run_creates_no_duplicates(settings, connection):
    first = run(settings, good_provider())
    second = run(settings, good_provider())

    assert second.succeeded == 0
    assert second.processed == 0
    assert second.skipped_existing == first.succeeded

    duplicates = query(connection, """
        SELECT anomaly_id FROM salesops.anomaly_hypotheses
        WHERE model_name = %(m)s
        GROUP BY anomaly_id, decision_version, prompt_version, model_name
        HAVING count(*) > 1
    """, {"m": TEST_MODEL})

    assert duplicates == []


def test_a_second_run_does_not_call_the_model_again(settings):
    """Idempotency has to be checked before the money is spent, not after."""
    run(settings, good_provider())

    second_provider = good_provider()
    run(settings, second_provider)

    assert second_provider.calls == []


def test_a_new_prompt_version_creates_a_new_row_beside_the_old_one(settings, connection):
    run(settings, good_provider(), only_dates=[LIVE_CRITICAL])
    run(settings, good_provider(), only_dates=[LIVE_CRITICAL],
        prompt_version=TEST_PROMPT_VERSION)

    rows = query(connection, """
        SELECT prompt_version FROM salesops.anomaly_hypotheses
        WHERE model_name = %(m)s AND calendar_date = %(d)s
        ORDER BY prompt_version
    """, {"m": TEST_MODEL, "d": LIVE_CRITICAL})

    assert [row["prompt_version"] for row in rows] == \
           sorted([prompts.PROMPT_VERSION, TEST_PROMPT_VERSION])


def test_a_different_model_creates_a_new_row_beside_the_old_one(settings, connection):
    run(settings, good_provider(TEST_MODEL), only_dates=[LIVE_CRITICAL])
    run(settings, good_provider(OTHER_MODEL), only_dates=[LIVE_CRITICAL])

    rows = query(connection, """
        SELECT model_name FROM salesops.anomaly_hypotheses
        WHERE calendar_date = %(d)s AND model_name IN (%(a)s, %(b)s)
    """, {"d": LIVE_CRITICAL, "a": TEST_MODEL, "b": OTHER_MODEL})

    assert len(rows) == 2


def test_regeneration_replaces_rather_than_duplicating(settings, connection):
    run(settings, good_provider(), only_dates=[LIVE_CRITICAL])

    before = query(connection, """
        SELECT hypothesis_id FROM salesops.anomaly_hypotheses
        WHERE model_name = %(m)s AND calendar_date = %(d)s
    """, {"m": TEST_MODEL, "d": LIVE_CRITICAL})[0]["hypothesis_id"]

    summary = run(settings, good_provider(), only_dates=[LIVE_CRITICAL], regenerate=True)

    after = query(connection, """
        SELECT hypothesis_id FROM salesops.anomaly_hypotheses
        WHERE model_name = %(m)s AND calendar_date = %(d)s
    """, {"m": TEST_MODEL, "d": LIVE_CRITICAL})

    assert summary.succeeded == 1
    assert summary.regenerated == 1
    assert len(after) == 1
    assert after[0]["hypothesis_id"] != before


def test_regeneration_is_never_implicit(settings):
    """The scheduled path must not be able to reach it.

    A nightly job that silently rewrote yesterday's reasoning would destroy the
    audit trail it exists to create.
    """
    import inspect
    signature = inspect.signature(service.run_analysis)

    assert signature.parameters["regenerate"].default is False


