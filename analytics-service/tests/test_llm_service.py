"""Stage 7 against the live warehouse, with a fake model.

The provider is faked; nothing else is. These run against real Stage 5 evidence
and real Stage 6 decisions, because the properties being tested are about how
Stage 7 behaves around them - eligibility, idempotency, and above all the
guarantee that no Stage 7 outcome, including total provider failure, can alter a
Stage 6 decision.

Skipped automatically when the stack is not running.

Every test that writes cleans up after itself by deleting only the rows it
created, keyed on a test-only model name. The live 90-day dataset is left as it
was found.
"""

