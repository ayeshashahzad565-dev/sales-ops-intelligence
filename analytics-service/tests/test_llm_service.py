def test_a_valid_hypothesis_is_persisted_with_full_provenance(settings, connection):
    run(settings, good_provider(), only_dates=[LIVE_CRITICAL])

    row = query(connection, """
        SELECT * FROM salesops.anomaly_hypotheses
        WHERE model_name = %(m)s AND calendar_date = %(d)s
    """, {"m": TEST_MODEL, "d": LIVE_CRITICAL})[0]

    assert row["model_provider"] == "mock"
    assert row["model_name"] == TEST_MODEL
    assert row["prompt_version"] == prompts.PROMPT_VERSION
    assert row["evidence_digest"] and len(row["evidence_digest"]) == 64
    assert row["generated_at"] is not None
    assert row["confidence"] in {"low", "medium", "high"}
    assert row["summary"].strip()
    assert row["primary_hypothesis"].strip()


