@pytest.mark.parametrize(
    "provider",
    [
        pytest.param(good_provider(), id="success"),
        pytest.param(StaticProvider(error=ProviderError("timed out"), model=TEST_MODEL),
                     id="timeout"),
        pytest.param(StaticProvider(error=RuntimeError("boom"), model=TEST_MODEL),
                     id="unexpected-exception"),
        pytest.param(StaticProvider(payload="{malformed", model=TEST_MODEL),
                     id="malformed-json"),
        pytest.param(StaticProvider(payload={"summary": "incomplete"}, model=TEST_MODEL),
                     id="schema-violation"),
        pytest.param(StaticProvider(payload=None, model=TEST_MODEL), id="empty-response"),
    ],
)
def test_no_stage6_decision_changes_whatever_the_model_does(settings, connection, provider):
    """The load-bearing test of the entire stage.

    Whatever the model returns - or fails to return - severity, routing,
    decision, notification permission and the review requirement are exactly as
    they were. Stage 7 has no code path that writes to anomaly_decisions; this
    asserts the absence against the live table.
    """
    before = decisions_snapshot(connection)

    run(settings, provider)

    assert decisions_snapshot(connection) == before


