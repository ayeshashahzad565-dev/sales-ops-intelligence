def test_only_actionable_decisions_are_analysed(settings, connection):
    provider = good_provider()
    summary = run(settings, provider)

    actionable = query(connection, """
        SELECT count(*) AS n FROM salesops.anomaly_decisions
        WHERE decision_version = 'stage6-v1' AND decision = 'action_required'
    """)[0]["n"]

    assert summary.eligible == actionable
    assert summary.succeeded == actionable


def test_no_action_decisions_are_never_sent_to_the_model(settings, connection):
    """The majority of days. Analysing them would spend money to explain that
    nothing happened."""
    provider = good_provider()
    run(settings, provider)

    analysed = {
        row["calendar_date"]
        for row in query(connection, """
            SELECT calendar_date FROM salesops.anomaly_hypotheses WHERE model_name = %(m)s
        """, {"m": TEST_MODEL})
    }

    no_action = {
        row["calendar_date"]
        for row in query(connection, """
            SELECT calendar_date FROM salesops.anomaly_decisions
            WHERE decision_version = 'stage6-v1' AND decision = 'no_action'
        """)
    }

    assert analysed
    assert not (analysed & no_action)
    assert LIVE_NORMAL_SUNDAY not in analysed


