def query(connection, sql: str, params: dict | None = None) -> list[dict]:
    with connection.cursor() as cursor:
        cursor.execute(sql, params or {})
        return cursor.fetchall()


def decisions_snapshot(connection) -> list[dict]:
    """Every Stage 6 field Stage 7 must never touch."""
    return query(connection, """
        SELECT decision_id, severity, routing, decision,
               notification_allowed, human_review_required, decision_reason_code
        FROM salesops.anomaly_decisions
        ORDER BY decision_id
    """)


def run(settings, provider, **kwargs):
    return service.run_analysis(settings=settings, provider=provider, **kwargs)


def good_provider(model: str = TEST_MODEL) -> StaticProvider:
    return StaticProvider(payload=valid_response(), model=model)


